/** Deduped, id-ascending view used by every page. */
const byId = new Map<number, Problem>();
for (const p of problems) if (!byId.has(p.id)) byId.set(p.id, p);

export const allProblems: Problem[] = [...byId.values()].sort((a, b) => a.id - b.id);
export const problemById = byId;

export function leetcodeURL(p: Problem): string {
  return `https://leetcode.com/problems/${p.leetcode}/`;
}

export function problemsForPattern(slug: string): Problem[] {
  return allProblems.filter((p) => p.patterns.includes(slug));
}
